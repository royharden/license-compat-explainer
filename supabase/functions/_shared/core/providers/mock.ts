import type { Provider } from './types.ts';
export const MOCK_MODEL = 'fixture@1';
export const MOCK_SCENARIOS = ['demo','all_invalid','wrong_passage','changed_case','foreign_id','verdict_key','options_key','extra_key','contradiction'] as const;
export type MockScenario = typeof MOCK_SCENARIOS[number];
export function mockProvider(scenario: MockScenario = 'demo', fixtures: Readonly<Record<string, unknown>> = {}): Provider {
  return { provider: 'mock', model: MOCK_MODEL,
    prepare(facts, maxOutputTokens) {
      const keys = facts.evaluation.ruleIds.map(id => `${id}__${scenario}`);
      const key = keys.find(k => Object.hasOwn(fixtures, k)) ?? keys[0];
      // Fixture bytes are supplied by the browser/Node harness, never generated by an LLM or fetched.
      return { provider: 'mock', model: MOCK_MODEL, maxOutputTokens, body: JSON.stringify({ key, output: fixtures[key] ?? null }) };
    },
    async complete(request) { const data = JSON.parse(request.body) as { output: unknown }; return { provider: 'mock', model: MOCK_MODEL,
      text: JSON.stringify(data.output), usage: { input_tokens: 0, output_tokens: 0 } }; },
  };
}
